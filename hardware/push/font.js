export function textWidth(text, scale) {
  return text.length * 6 * scale - scale;
}

/** Draw uppercase text into a bufferWidth-wide RGBA buffer. */
export function drawText(buffer, bufferWidth, text, startX, startY, scale, [r, g, b]) {
  let penX = Math.round(startX);
  const penY = Math.round(startY);
  for (const char of text.toUpperCase()) {
    const glyph = GLYPHS[char];
    if (glyph !== undefined) {
      for (let row = 0; row < 7; row++) {
        for (let col = 0; col < 5; col++) {
          if (glyph[row][col] === "1") {
            fillRect(buffer, bufferWidth,
              penX + col * scale, penY + row * scale, scale, scale, r, g, b);
          }
        }
      }
    }
    penX += 6 * scale;
  }
}

export function fillRect(buffer, bufferWidth, x, y, width, height, r, g, b) {
  const bufferHeight = buffer.length / 4 / bufferWidth;
  const x1 = Math.max(0, Math.round(x));
  const y1 = Math.max(0, Math.round(y));
  const x2 = Math.min(bufferWidth, Math.round(x + width));
  const y2 = Math.min(bufferHeight, Math.round(y + height));
  for (let py = y1; py < y2; py++) {
    let offset = (py * bufferWidth + x1) * 4;
    for (let px = x1; px < x2; px++) {
      buffer[offset] = r;
      buffer[offset + 1] = g;
      buffer[offset + 2] = b;
      offset += 4;
    }
  }
}
